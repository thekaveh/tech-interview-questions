#!/usr/bin/env python3
"""Build PROBLEMS.md — a flat browsable index of every problem in the repo.

Walks java/src/main/java/, reads each problem's README.md (expecting the
standard `# <Title>` + badge + `**Source:**` lines + solutions table), and
writes a single sortable markdown table grouped by provider/tier to
PROBLEMS.md at the repo root.

Re-run after adding a new problem; commit the regenerated file.
"""

import re
import sys
from collections import defaultdict
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
JAVA_ROOT = REPO / 'java' / 'src' / 'main' / 'java'
OUT = REPO / 'PROBLEMS.md'

DIFFICULTY_ORDER = {
    'warm-up': 0,
    'easy': 1,
    'medium': 2,
    'hard': 3,
    'very-hard': 4,
}

BADGE_RE = re.compile(r'badge/difficulty-([a-z-]+?)-[a-z]+\)')

PROVIDER_LABELS = {
    'algoexpert': 'AlgoExpert',
    'codesignal': 'CodeSignal',
    'educative': 'Educative',
}

TIER_LABELS = {
    'easy': 'Easy',
    'medium': 'Medium',
    'hard': 'Hard',
    'veryhard': 'Very Hard',
    'intro': 'Intro',
    'thecore': 'The Core',
}


def label_tier(provider: str, tier: str) -> str:
    if provider == 'educative':
        return tier.replace('_', ' ').title()
    return TIER_LABELS.get(tier, tier)


def read_problem(readme: Path) -> dict | None:
    text = readme.read_text()
    lines = text.splitlines()
    if not lines or not lines[0].startswith('# '):
        return None
    title = lines[0][2:].strip()
    rel = readme.parent.relative_to(JAVA_ROOT).parts
    provider = rel[0]
    if provider == 'educative':
        tier = rel[2] if len(rel) > 2 else rel[1]
    else:
        tier = rel[1]
    n_solutions = len(list(readme.parent.glob('Solution*.java')))
    badge_match = BADGE_RE.search(text)
    difficulty = badge_match.group(1).replace('--', '-') if badge_match else 'easy'
    rel_path = readme.parent.relative_to(REPO).as_posix()
    return {
        'title': title,
        'provider': provider,
        'tier': tier,
        'difficulty': difficulty,
        'n_solutions': n_solutions,
        'path': rel_path,
    }


def main() -> int:
    problems = []
    for readme in JAVA_ROOT.rglob('README.md'):
        p = read_problem(readme)
        if p is not None:
            problems.append(p)

    by_group: dict[tuple[str, str], list[dict]] = defaultdict(list)
    for p in problems:
        by_group[(p['provider'], p['tier'])].append(p)

    counts_by_provider: dict[str, list[int]] = defaultdict(lambda: [0, 0])
    for p in problems:
        counts_by_provider[p['provider']][0] += 1
        counts_by_provider[p['provider']][1] += p['n_solutions']

    out = ['# Problem Index', '']
    out.append('Auto-generated by `scripts/generate_problem_index.py`. '
               'Re-run after adding or renaming a problem.')
    out.append('')
    out.append(f'**Total:** {len(problems)} problems across '
               f"{sum(p['n_solutions'] for p in problems)} solutions.")
    out.append('')
    out.append('| Provider | Problems | Solutions |')
    out.append('|---|---:|---:|')
    for provider in ('algoexpert', 'codesignal', 'educative'):
        counts = counts_by_provider.get(provider)
        if counts is None:
            continue
        out.append(f'| {PROVIDER_LABELS[provider]} | {counts[0]} | {counts[1]} |')
    out.append('')
    out.append('## By provider and tier')
    out.append('')

    for provider in ('algoexpert', 'codesignal', 'educative'):
        groups = [(t, by_group[(p, t)]) for (p, t) in by_group if p == provider]
        if not groups:
            continue
        out.append(f'### {PROVIDER_LABELS[provider]}')
        out.append('')
        for tier, plist in sorted(groups, key=lambda g: DIFFICULTY_ORDER.get(g[1][0]['difficulty'], 99)):
            out.append(f'#### {label_tier(provider, tier)} ({len(plist)})')
            out.append('')
            out.append('| Problem | Difficulty | # Solutions |')
            out.append('|---|---|---:|')
            for p in sorted(plist, key=lambda x: x['title'].lower()):
                out.append(f"| [{p['title']}]({p['path']}/) | {p['difficulty']} | {p['n_solutions']} |")
            out.append('')

    OUT.write_text('\n'.join(out) + '\n')
    print(f'wrote {OUT} ({len(problems)} problems)')
    return 0


if __name__ == '__main__':
    sys.exit(main())
