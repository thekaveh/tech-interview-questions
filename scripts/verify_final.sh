#!/usr/bin/env bash
# Run after every migration commit to confirm the repo is in a clean
# end state. Fails fast on any issue. Designed for the
# repo-restructure branch; safe to run repeatedly.

set -uo pipefail

REPO_ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$REPO_ROOT"

step() { printf "\n=== %s ===\n" "$*"; }
fail() { printf "FAIL: %s\n" "$*" >&2; exit 1; }

# count_matches PATTERN PATH... -- returns line count, never errors
count_matches() {
    local pattern="$1"; shift
    grep -rln "$pattern" "$@" 2>/dev/null | wc -l | tr -d ' '
}

step "Maven compile"
( cd java && mvn -B -q compile ) || fail "mvn compile failed"
echo "ok"

step "Migration tool unit tests"
python3 -m unittest discover -s scripts -p "test_*.py" >/dev/null 2>&1 || fail "unit tests failed"
echo "ok"

step "No '// Approach: TODO.' placeholders remain in Java sources"
n=$(count_matches "// Approach: TODO\." java/src/main/java)
[ "$n" -eq 0 ] || fail "$n Solution.java files still carry '// Approach: TODO.'"
echo "ok"

step "No 'TODO' rows in problem README solution tables"
n=$(count_matches "| TODO | TODO | TODO |" java/src/main/java)
[ "$n" -eq 0 ] || fail "$n READMEs still carry TODO rows"
echo "ok"

step "No 'paraphrase the problem' TODO comments remain in READMEs"
n=$(count_matches "TODO: paraphrase the problem" java/src/main/java)
[ "$n" -eq 0 ] || fail "$n READMEs still carry the paraphrase TODO marker"
echo "ok"

step "Every problem README uses the '## 1. Problem' + '## 2. Solutions' structure"
total=$(find java/src/main/java -name 'README.md' | wc -l | tr -d ' ')
with_problem=$(count_matches "^## 1. Problem" java/src/main/java)
with_solutions=$(count_matches "^## 2. Solutions" java/src/main/java)
[ "$total" -eq "$with_problem" ] || fail "$with_problem/$total READMEs have '## 1. Problem'"
[ "$total" -eq "$with_solutions" ] || fail "$with_solutions/$total READMEs have '## 2. Solutions'"
echo "$total/$total"

step "No 'Co-Authored-By:' trailers in branch commit history"
n=$(git log 8e95a2e..HEAD --format=%B 2>/dev/null | grep -c "^Co-Authored-By:" || true)
if [ "$n" -ne 0 ]; then
    git log 8e95a2e..HEAD --format=%B | grep "^Co-Authored-By:" >&2
    fail "$n commit message(s) carry a 'Co-Authored-By:' trailer"
fi
echo "ok"

step "No 'Claude' or 'AI' attributions in commit message bodies"
suspects=$(git log 8e95a2e..HEAD --format=%B 2>/dev/null | grep -iE "with claude|claude as|by claude|generated by|claude generated|coauthored.*ai|ai.coauthor" || true)
if [ -n "$suspects" ]; then
    printf "%s\n" "$suspects" >&2
    fail "commit message body mentions an AI coauthor"
fi
echo "ok"

step "Legacy provider directories absent"
for legacy in algoexpert.io codesignal.com educative.io; do
    [ ! -d "$legacy" ] || fail "legacy directory still exists: $legacy"
done
echo "ok"

step "Source tree shape"
n_java=$(find java/src/main/java -name '*.java' | wc -l | tr -d ' ')
n_readme=$(find java/src/main/java -name 'README.md' | wc -l | tr -d ' ')
echo "java files: $n_java"
echo "READMEs:    $n_readme"
[ "$n_java" -gt 0 ] || fail "no .java files found under java/src/main/java"
[ "$n_readme" -gt 0 ] || fail "no README.md files found under java/src/main/java"

printf "\nALL CHECKS PASSED\n"
